"""Rotate only a fixture-owned loopback SSH listener, with two real delegated VMs.

No system SSH configuration, installed engine, or existing listener is changed.
The existing disposable client's PUBLIC companion authorizes the fixture listener.
Generated host private keys stay in this run's Linux scratch directory.
"""
import argparse
import base64
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import signal
import subprocess
import time

spec = importlib.util.spec_from_file_location("home", Path(__file__).with_name("remote-home.py"))
home = importlib.util.module_from_spec(spec)
spec.loader.exec_module(home)


def public(path):
    key = " ".join(path.read_text(encoding="utf-8").split()[:2])
    blob = base64.b64decode(key.split()[1], validate=True)
    return {"public_key": key, "pin": "SHA256:" + base64.b64encode(hashlib.sha256(blob).digest()).decode().rstrip("=")}


class Listener:
    operations = {"rotate"}

    def __init__(self, args):
        self.args, self.process, self.log = args, None, None

    def configure(self, key):
        # Paths are generated by this fixture under an explicit fresh absolute root.
        for path in (key, self.directory, self.client):
            assert path.is_absolute() and not any(c.isspace() for c in str(path))
        self.config.write_text(f"""Port {self.args.port}
ListenAddress 127.0.0.1
AddressFamily inet
HostKey {key}
PidFile {self.directory / 'listener.pid'}
AuthorizedKeysFile {self.client}
PermitRootLogin prohibit-password
AllowUsers root
PasswordAuthentication no
KbdInteractiveAuthentication no
AuthenticationMethods publickey
UsePAM no
StrictModes yes
AllowAgentForwarding no
AllowTcpForwarding no
X11Forwarding no
PermitTunnel no
PermitTTY no
PermitUserEnvironment no
LogLevel VERBOSE
""", encoding="utf-8")

    def await_key(self, expected):
        until = time.monotonic() + 12
        while time.monotonic() < until:
            assert self.process.poll() is None, "Owned SSH listener exited; inspect its log"
            scan = subprocess.run(["/usr/bin/ssh-keyscan", "-T", "1", "-p", str(self.args.port),
                                   "-t", "ed25519", "127.0.0.1"], capture_output=True, timeout=3)
            keys = [" ".join(line.split()[-2:]) for line in scan.stdout.decode().splitlines() if not line.startswith("#")]
            if expected in keys:
                return
            time.sleep(0.1)
        raise AssertionError("Owned listener did not present its fixture-generated key")

    def start(self, run):
        self.run = run
        self.directory = run.root / "ssh-listener"
        self.directory.mkdir(mode=0o700)
        self.client = self.args.host_public_key.with_name("client.pub").resolve(strict=True)
        self.keys = [self.directory / name for name in ("host-first", "host-rotated")]
        for key in self.keys:
            subprocess.run(["/usr/bin/ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", str(key)], check=True)
        self.config = self.directory / "sshd_config"
        self.configure(self.keys[0])
        subprocess.run(["/usr/sbin/sshd", "-t", "-f", str(self.config)], check=True)
        self.log = (self.directory / "listener.log").open("wb")
        self.process = subprocess.Popen(["/usr/sbin/sshd", "-D", "-e", "-f", str(self.config)],
                                        stdin=subprocess.DEVNULL, stdout=self.log, stderr=self.log, start_new_session=True)
        pub = Path(str(self.keys[0]) + ".pub")
        self.await_key(public(pub)["public_key"])
        return pub

    def call(self, request):
        assert request["op"] == "rotate" and self.process.poll() is None
        self.configure(self.keys[1])
        # Reload only this Popen-owned listener. Existing authenticated sessions
        # remain alive; the next management connection must detect the new key.
        os.kill(self.process.pid, signal.SIGHUP)
        result = public(Path(str(self.keys[1]) + ".pub"))
        self.await_key(result["public_key"])
        self.run.write("fixture-key-rotated", result)
        return result

    def close(self):
        if self.process and self.process.poll() is None:
            self.process.terminate()
            try:
                self.process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=10)
        if self.log:
            self.log.close()


class Rotation(home.Home):
    def saved_profile(self, args, info, label):
        profile = {"name": label, "vendor": "other", "host": "127.0.0.1", "port": args.port,
                   "username": "root", "identityFile": str(args.identity.resolve()), "hostKey": info["public_key"]}
        result = self.result("add_cloud_environment", {"request": profile}, label)
        return next(e["id"] for e in result["environments"] if e["name"] == label)

    def run_rotation(self, args, server):
        self.start()
        initial = server.info
        connection = self.saved_profile(args, initial, "before-rotation")
        launch = {"connection": connection, "parent": self.parent(), "program": initial["program"],
                  "endpoint": initial["endpoint"], "engine_sha256": initial["engine_sha256"],
                  "memory_mib": 512, "lifetime_seconds": 300}
        # Explicit first-use trust does not create a parent or remote workload.
        trust = self.remote("trust", "first-use-owner-trust", connection=connection, accept_host_key=initial["pin"])
        assert trust["new_authority"] is False and trust["cleanup_pending"] == 0
        first = self.remote("launch", "first-launch", **launch)["run"]
        first_ready = self.phase(first, {"ready"}, "first-ready")
        second = self.remote("launch", "second-launch", **launch)["run"]
        second_ready = self.phase(second, {"ready"}, "second-ready")
        runs = {first: first_ready["observation"], second: second_ready["observation"]}
        for observed in runs.values():
            server.call("watch", identity=observed["process"])
        assert not self.remote("trust", "live-rotation-refused", False, connection=connection, accept_host_key=initial["pin"])["ok"]
        ordinary = server.call("vm", label="ordinary-before-rotation", params={"action": "launch", "memoryGb": 0.5})
        rotated = server.call("rotate")
        assert rotated["pin"] != initial["pin"]
        for index, run in enumerate(runs):
            assert self.remote("status", f"old-channel-survives-reload-{index}", run=run)["phase"] == "ready"
        refused = self.remote("start", "actual-mismatched-host-refused", False, run=first, input_hex=b"printf must-not-run".hex())
        assert not refused["ok"]
        for index, (run, observed) in enumerate(runs.items()):
            self.phase(run, {"unconfirmed"}, f"shared-rejection-{index}", timeout=25)
            self.wait_native(server, observed, f"native-end-{index}")
        hosts = list((self.data / "sandbox-vm/remote-home/hosts").glob("*.json"))
        assert len(hosts) == 1
        rejected = json.loads(hosts[0].read_text(encoding="utf-8"))
        assert rejected["known"]["rejections"], "No real host-key rejection was persisted"
        self.write("persisted-rejection", rejected)
        survived = server.call("vm", label="ordinary-survives-rotation", params={"action": "exec", "sandbox": ordinary["sandbox"], "input": "printf still-running"})
        assert "still-running" in survived["output_text"]
        self.process.kill(); self.process.wait(timeout=20)
        self.start()
        for run in runs:
            self.phase(run, {"unconfirmed"}, "restart-keeps-rejection")
        restored = json.loads(hosts[0].read_text(encoding="utf-8"))
        assert restored["known"]["rejections"] == rejected["known"]["rejections"]
        launch["parent"] = self.parent()
        assert not self.remote("launch", "old-key-stays-rejected", False, **launch, accept_host_key=initial["pin"])["ok"]
        connection2 = self.saved_profile(args, rotated, "after-rotation")
        launch["connection"] = connection2
        assert not self.remote("launch", "profile-alias-cannot-forgive-rejection", False, **launch, accept_host_key=rotated["pin"])["ok"]
        assert not self.remote("trust", "wrong-rotation-pin-refused", False, connection=connection2, accept_host_key=initial["pin"])["ok"]
        time.sleep(0.2)  # Let the already-failed recovery workers release their holders.
        confirmed = self.remote("trust", "owner-confirms-new-key", connection=connection2, accept_host_key=rotated["pin"])
        assert confirmed["new_authority"] is False and confirmed["cleanup_pending"] == 2
        for index, (run, observed) in enumerate(runs.items()):
            ended = self.phase(run, {"ended"}, f"old-native-cleanup-{index}")
            assert ended["receipt"]["proof"]["process"] == observed["process"]
            record = json.loads((self.data / f"sandbox-vm/remote-home/runs/{run}.json").read_text(encoding="utf-8"))
            assert record["profile"]["hostKey"] == initial["public_key"]
            assert record["cleanup_profile"]["hostKey"] == rotated["public_key"]
            assert record["observation"] == observed
        changed = json.loads(hosts[0].read_text(encoding="utf-8"))
        assert changed["known"]["rejections"] == rejected["known"]["rejections"]
        assert changed["retired"] and changed["known"]["next"] > rejected["known"]["next"]
        self.write("new-enrollment-keeps-history", changed)
        assert not self.remote("launch", "cleanup-did-not-enable-work", False, **launch)["ok"]
        last = self.remote("launch", "new-owner-authorized-launch", **launch, accept_host_key=rotated["pin"])["run"]
        self.phase(last, {"ready"}, "new-key-ready")
        command = self.work(last, "printf rotated", "new-key-command")
        outcome = self.outcome(last, command["command"], "new-key-output")
        assert outcome["exit_code"] == 0 and bytes.fromhex(outcome["output"]) == b"rotated"
        self.remote("stop", "stop-new-run", run=last)
        self.phase(last, {"ended"}, "new-run-ended")
        server.call("vm", label="stop-ordinary", params={"action": "stop", "sandbox": ordinary["sandbox"]})
        for sandbox in self.sandboxes:
            self.call("sandbox_vm", {"action": "stop", "sandbox": sandbox}, "stop-parent", checked=False)
        self.wait_no_qemu()
        assert not self.result("model_ledger", {}, "final-home-ledger")["open"]
        assert not server.call("clean")["ledger"]["open"]
        self.stop()
        self.write("rotation-result", {"passed": True, "checks": ["explicit-first-trust", "live-holder-refusal",
            "old-channels-survive-reload", "actual-host-mismatch", "shared-rejection", "exact-native-ends", "ordinary-isolation", "restart-keeps-rejection",
            "alias-cannot-forgive", "exact-owner-pin", "grant-free-old-cleanup", "immutable-launch-identity",
            "retained-generation-history", "fresh-owner-authority", "zero-accounting"]})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    home.arguments(parser)
    parser.add_argument("--server", action="store_true")
    parser.add_argument("--host-public-key", type=Path)
    parser.add_argument("--distro")
    for name in ("server-script", "server-root", "server-engine", "server-cli", "server-runtime", "server-host-public-key"):
        parser.add_argument("--" + name)
    parser.add_argument("--identity", type=Path)
    parser.add_argument("--port", type=int, default=22844)
    args = parser.parse_args()
    if args.server:
        assert os.name == "posix"
        home.server(args, Listener(args))
    else:
        assert os.name == "nt"
        args.reuse_fixture, args.from_case, args.model, args.fixture = False, None, args.engine.parent, args.engine
        run, remote = Rotation(args), None
        try:
            remote = home.Server(args, run.root)
            run.run_rotation(args, remote)
        finally:
            if run.process and run.process.poll() is None:
                for sandbox in run.sandboxes:
                    run.call("sandbox_vm", {"action": "stop", "sandbox": sandbox}, "fixture-cleanup", checked=False)
                run.stop()
            if remote:
                remote.close()
