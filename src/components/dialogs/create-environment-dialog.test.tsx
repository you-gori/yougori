it("waits for an image import before allowing creation, cancellation or changing the workflow", async () => {
  let finish!: (image: Awaited<ReturnType<typeof sandboxVmApi.importImage>>) => void
  vi.mocked(sandboxVmApi.importImage).mockReturnValue(new Promise(resolve => { finish = resolve }))
  const close = vi.fn()
  render(<CreateEnvironmentDialog open onOpenChange={close} />)
  fireEvent.click(screen.getByRole("combobox", { name: "OCI image" }))
  await userEvent.click(await screen.findByRole("button", { name: "Use custom image" }))
  expect(screen.getByRole("button", { name: "Create environment" })).toBeDisabled()
  fireEvent.change(screen.getByLabelText("Image source"), { target: { value: "layout" } })
  fireEvent.change(screen.getByLabelText("Layout folder"), { target: { value: "C:/images/app" } })
  fireEvent.click(screen.getByLabelText("I choose this unsigned image for my own sandboxes."))
  fireEvent.click(screen.getByRole("button", { name: "Import image" }))
  expect(screen.getByRole("button", { name: "Create environment" })).toBeDisabled()
  expect(screen.getByRole("button", { name: "Cancel" })).toBeDisabled()
  expect(screen.getByRole("button", { name: "Close" })).toBeDisabled()
  expect(screen.getByRole("radio", { name: "Cloud environment" })).toHaveAttribute("aria-disabled", "true")
  fireEvent.click(screen.getByRole("radio", { name: "Cloud environment" }))
  expect(screen.getByRole("radio", { name: "Sandbox VM" })).toBeChecked()
  expect(sandboxVmApi.launch).not.toHaveBeenCalled()
  const image = { id: "sha256:test", image: { root_bytes: 2 ** 30, process: { entrypoint: ["/app"], cmd: [] } } }
  vi.mocked(sandboxVmApi.images).mockResolvedValue([image])
  finish(image)
  await waitFor(() => expect(screen.getByRole("button", { name: "Create environment" })).not.toBeDisabled())
  expect(screen.getByLabelText("Memory value")).toHaveValue(1.5)
  fireEvent.click(screen.getByRole("button", { name: "Create environment" }))
  await waitFor(() => expect(close).toHaveBeenCalledWith(false))
  expect(sandboxVmApi.launch).toHaveBeenCalledExactlyOnceWith({ image: image.id, cpu: 1, memoryGb: 1.5 })
})

