it("launches a real VM request with its workspace and refreshes the inventory before opening it", async () => {
  const close = vi.fn()
  const opened = vi.fn()
  window.addEventListener("yougori-open-sandbox-vm", opened)
  render(<CreateEnvironmentDialog open onOpenChange={close} />)
  fireEvent.change(screen.getByLabelText(/Folder it works on/), { target: { value: "C:/work/project" } })
  fireEvent.change(screen.getByLabelText("Memory value"), { target: { value: "2" } })
  fireEvent.change(screen.getByLabelText("CPU value"), { target: { value: "4" } })
  fireEvent.click(screen.getByRole("button", { name: "Create environment" }))
  await waitFor(() => expect(close).toHaveBeenCalledWith(false))
  expect(sandboxVmApi.launch).toHaveBeenCalledExactlyOnceWith({ cpu: 4, memoryGb: 2, workspace: "C:/work/project" })
  expect(refresh).toHaveBeenCalledOnce()
  expect(opened.mock.calls[0]?.[0].detail).toBe("vm-new")
  window.removeEventListener("yougori-open-sandbox-vm", opened)
})

it("prevents duplicate launches and preserves the form when the engine refuses creation", async () => {
  let reject!: (reason: Error) => void
  vi.mocked(sandboxVmApi.launch).mockReturnValue(new Promise((_, fail) => { reject = fail }))
  const close = vi.fn()
  render(<CreateEnvironmentDialog open onOpenChange={close} />)
  const create = screen.getByRole("button", { name: "Create environment" })
  fireEvent.click(create); fireEvent.click(create)
  expect(sandboxVmApi.launch).toHaveBeenCalledOnce()
  expect(create).toBeDisabled()
  reject(new Error("Not enough memory"))
  expect(await screen.findByRole("alert")).toHaveTextContent("Not enough memory")
  expect(close).not.toHaveBeenCalled()
  expect(create).not.toBeDisabled()
})

